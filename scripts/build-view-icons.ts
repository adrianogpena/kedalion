import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(import.meta.dir, '../packages/ui/src/assets/views');
const entries = readdirSync(dir).filter((f) => f.endsWith('.svg')).sort().map((f) => `  ${f.replace('.svg', '')}: ${JSON.stringify(readFileSync(join(dir, f), 'utf8').trim())},`);
writeFileSync(join(dir, '../../view-icon-markup.ts'), `// Generated by scripts/build-view-icons.ts from assets/views/*.svg; do not edit.\nexport const VIEW_ICON_MARKUP: Record<string, string> = {\n${entries.join('\n')}\n};\n`);
